"""Turn content/content.js into an English-only copy for the desktop app.

Usage: make_english.py <path/to/content.js>   (rewrites the file in place)
Every {"en": ..., "sk": ...} value becomes its English string, and
config.languages is set to ["en"], which hides the language switch.
"""
import json
import sys

PREFIX = "window.PORTFOLIO = "


def english(value):
    if isinstance(value, dict):
        if set(value) <= {"en", "sk"} and "en" in value:
            return english(value["en"])
        return {k: english(v) for k, v in value.items()}
    if isinstance(value, list):
        return [english(v) for v in value]
    return value


def main(path):
    text = open(path, encoding="utf-8").read()
    start = text.index(PREFIX) + len(PREFIX)
    end = text.rstrip().rstrip(";").rstrip()
    data = json.loads(text[start:len(end)])
    data = english(data)
    data["config"]["languages"] = ["en"]
    data["config"]["defaultLanguage"] = "en"
    with open(path, "w", encoding="utf-8") as f:
        f.write("/* English-only build for the desktop app. Generated by desktop/make_english.py. */\n")
        f.write(PREFIX + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")


if __name__ == "__main__":
    main(sys.argv[1])
